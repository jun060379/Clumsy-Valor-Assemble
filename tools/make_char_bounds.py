#!/usr/bin/env python3
"""Per-cell vertical extent of the character sheets for 캐릭터 도트화 (charPix's "lit from above" ramp).
Writes scripts/char_bounds.gd: for each character, [top, bottom] source rows (alpha > 100) of every 448x352 cell,
indexed (row * 9 + col) * 2 over the five sheets (row = sheet * 7 + row in sheet). -1 for an empty cell."""
import sys, os
import numpy as np
from PIL import Image
ROOT = os.path.join(os.path.dirname(__file__), '..')
out = ['## generated by tools/make_char_bounds.py: [top, bottom] source rows (alpha > 100) per 448x352 cell, (row * 9 + col) * 2', 'extends RefCounted',
       'const B := {']
for c in ['estelle', 'aida', 'luce']:
    vals = []
    for k in range(5):
        a = np.asarray(Image.open(f'{ROOT}/assets/chars/{c}/{c}_{k}.png').convert('RGBA'))[..., 3]
        for r in range(7):
            for f in range(9):
                cell = a[r*352:(r+1)*352, f*448:(f+1)*448]
                rows = np.nonzero((cell > 100).any(axis=1))[0]
                vals += [int(rows[0]), int(rows[-1])] if len(rows) else [-1, -1]
    out.append(f'\t"{c}": {vals},')
out.append('}')
open(f'{ROOT}/scripts/char_bounds.gd', 'w').write('\n'.join(out) + '\n')
