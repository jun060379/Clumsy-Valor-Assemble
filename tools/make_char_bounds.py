#!/usr/bin/env python3
"""Per-cell vertical extent of the character sheets for 캐릭터 도트화 (charPix's "lit from above" ramp).
Writes scripts/char_bounds.gd: for each character, [top, bottom] source rows (alpha > 100) of every 448x352 cell,
indexed (row * 9 + col) * 2 over the five sheets (row = sheet * 7 + row in sheet). -1 for an empty cell.

  --skin <id>   a costume instead: reads assets/skins/<id>/sheet_*.png and writes assets/skins/<id>/bounds.gd as
                {row: [top, bottom] x 9} for every row that has art (skins.gd merges it over the original rows).
                Optional: without it a costume's rows borrow the original's (close enough when the poses match)."""
import sys, os, glob
import numpy as np
from PIL import Image
ROOT = os.path.join(os.path.dirname(__file__), '..')


def cells(path):
    a = np.asarray(Image.open(path).convert('RGBA'))[..., 3]
    for r in range(7):
        vals = []
        for f in range(9):
            cell = a[r*352:(r+1)*352, f*448:(f+1)*448]
            rows = np.nonzero((cell > 100).any(axis=1))[0]
            vals += [int(rows[0]), int(rows[-1])] if len(rows) else [-1, -1]
        yield r, vals


if len(sys.argv) > 2 and sys.argv[1] == '--skin':
    sid = sys.argv[2]
    d = f'{ROOT}/assets/skins/{sid}'
    out = {}
    for p in sorted(glob.glob(f'{d}/sheet_*.png')):
        si = int(os.path.basename(p)[6:-4])
        for r, vals in cells(p):
            if any(v >= 0 for v in vals): out[si * 7 + r] = vals
    with open(f'{d}/bounds.gd', 'w') as fh:
        fh.write(f'## generated by tools/make_char_bounds.py --skin {sid}: [top, bottom] source rows (alpha > 100) of each cell of its rows\n')
        fh.write('extends RefCounted\nconst B := {\n' + ''.join(f'\t{r}: {v},\n' for r, v in sorted(out.items())) + '}\n')
    sys.exit(0)

out = ['## generated by tools/make_char_bounds.py: [top, bottom] source rows (alpha > 100) per 448x352 cell, (row * 9 + col) * 2', 'extends RefCounted',
       'const B := {']
for c in ['estelle', 'aida', 'luce', 'kenin']:
    vals = []
    for k in range(5):
        for r, v in cells(f'{ROOT}/assets/chars/{c}/{c}_{k}.png'): vals += v
    out.append(f'\t"{c}": {vals},')
out.append('}')
open(f'{ROOT}/scripts/char_bounds.gd', 'w').write('\n'.join(out) + '\n')
